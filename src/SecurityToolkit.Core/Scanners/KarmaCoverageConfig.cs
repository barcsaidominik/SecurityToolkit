namespace SecurityToolkit.Core.Scanners;

/// <summary>
/// The per-run Karma config <see cref="SonarScanner"/> passes to <c>ng test --karma-config</c>.
/// Angular's built-in Karma config only emits html + text-summary coverage, never the lcov file
/// Sonar imports, so this replicates the built-in config (same plugins, resolved from the Angular
/// workspace's own node_modules) with an lcov-only reporter writing into the scan's results
/// directory. lcov only: the html reporter copies source code, which Gitleaks' working-tree scan
/// would then report a second time.
/// </summary>
public static class KarmaCoverageConfig
{
    /// <summary>Custom launcher name the scanner passes as <c>--browsers</c>; honors CHROME_BIN like karma-chrome-launcher's own ChromeHeadless.</summary>
    public const string LauncherName = "ChromeHeadlessToolkit";

    public static string Build(string coverageDirectory)
    {
        var directoryLiteral = System.Text.Json.JsonSerializer.Serialize(coverageDirectory);

        return $$"""
            // Generated by security-toolkit for one scan run; never edited by hand.
            const { createRequire } = require('node:module');
            const workspaceRequire = createRequire(process.cwd() + '/');

            module.exports = function (config) {
              config.set({
                basePath: '',
                frameworks: ['jasmine'],
                plugins: ['karma-jasmine', 'karma-chrome-launcher', 'karma-coverage'].map((p) => workspaceRequire(p)),
                coverageReporter: {
                  dir: {{directoryLiteral}},
                  subdir: '.',
                  reporters: [{ type: 'lcovonly', file: 'lcov.info' }, { type: 'text-summary' }],
                },
                reporters: ['progress'],
                browsers: ['{{LauncherName}}'],
                customLaunchers: {
                  {{LauncherName}}: {
                    base: 'ChromeHeadless',
                    flags: ['--no-sandbox', '--disable-gpu', '--disable-dev-shm-usage'],
                  },
                },
                singleRun: true,
                restartOnFileChange: false,
              });
            };
            """;
    }
}
